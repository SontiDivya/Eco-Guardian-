@app.route("/admin")
def admin_page():
    role = current_role()

    if role != "admin":

        # Nobody signed in: send them home to log in first.
        # A signed-in non-admin gets a clear refusal.

        if not session.get("username"):
            return redirect("/")

        return (
            "Administrator access only. Sign in with an administrator account.",
            403,
            {"Content-Type": "text/plain; charset=utf-8"},
        )

    return render_template("admin.html")


@app.route("/api/admin/reports")
def admin_reports():
    denied = admin_only()

    if denied:
        return denied

    connection = connect()

    counts = report_counts(connection)

    rows = connection.execute(
        """
        SELECT id, name, issue, description, address, status, created_at
        FROM reports
        ORDER BY created_at DESC, id DESC
        """
    ).fetchall()

    connection.close()

    reports = [
        {
            "id": row[0],
            "name": row[1],
            "issue": row[2],
            "description": row[3],
            "address": row[4],
            "status": row[5],
            "created_at": row[6],
        }
        for row in rows
    ]

    return jsonify({"counts": counts, "reports": reports})


@app.route("/api/admin/reports/<int:report_id>/status", methods=["POST"])
def admin_set_status(report_id):
    denied = admin_only()

    if denied:
        return denied

    data = request.get_json(silent=True) or {}
    status = str(data.get("status") or "").strip()

    if status not in REPORT_STATUSES:
        return jsonify({
            "error": "Status must be Pending, In Progress or Resolved."
        }), 400

    connection = connect()

    cursor = connection.execute(
        "UPDATE reports SET status = %s WHERE id = %s",
        (status, report_id),
    )

    if cursor.rowcount == 0:
        connection.close()

        return jsonify({"error": "That report no longer exists."}), 404

    connection.commit()

    counts = report_counts(connection)

    connection.close()

    print("Report", report_id, "->", status)

    return jsonify({
        "ok": True,
        "id": report_id,
        "status": status,
        "counts": counts,
    })


