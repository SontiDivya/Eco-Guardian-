# Create the tables and columns if they do not exist yet (safe every start)
def ensure_schema():
    """Create the PostgreSQL tables if they do not exist yet.

    The DDL is identical to the one in migrate_sqlite_to_neon.py, so the
    application and the migration script can never drift apart.
    """

    connection = connect()
    cursor = connection.cursor()

    # One pending login code per mobile number, replaced on every request

    cursor.execute(
        """
        CREATE TABLE IF NOT EXISTS otps (
            phone TEXT PRIMARY KEY,
            code TEXT NOT NULL,
            expires_at BIGINT NOT NULL,
            attempts INTEGER NOT NULL DEFAULT 0,
            requested_at BIGINT NOT NULL
        )
        """
    )

    # Registered members: username + password

    cursor.execute(
        """
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            created_at TEXT NOT NULL DEFAULT (
                to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
            ),
            role TEXT NOT NULL DEFAULT 'user'
        )
        """
    )

    # Reported issues. created_at keeps the same UTC text format SQLite used.

    cursor.execute(
        """
        CREATE TABLE IF NOT EXISTS reports (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            issue TEXT NOT NULL,
            description TEXT NOT NULL,
            created_at TEXT DEFAULT (
                to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')
            ),
            status TEXT NOT NULL DEFAULT 'Pending',
            address TEXT NOT NULL DEFAULT ''
        )
        """
    )

    # Columns that were added after the tables were first created

    cursor.execute(
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'user'"
    )
    cursor.execute(
        "ALTER TABLE reports ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'Pending'"
    )
    cursor.execute(
        "ALTER TABLE reports ADD COLUMN IF NOT EXISTS address TEXT NOT NULL DEFAULT ''"
    )

    # Repair the users.created_at default on tables created by an earlier
    # build of this file: SQLite's datetime('now','localtime') spelling is
    # rejected by PostgreSQL. Safe to run on every start.

    cursor.execute(
        "ALTER TABLE users ALTER COLUMN created_at "
        "SET DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')"
    )

    connection.commit()
    connection.close()


ensure_schema()


