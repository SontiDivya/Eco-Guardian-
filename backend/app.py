# Accounts: username + password
# ==========================================

PASSWORD_ITERATIONS = 100000

USERNAME_PATTERN = re.compile(r"^[A-Za-z0-9_]{3,20}$")


def hash_password(password):
    """Store a password as pbkdf2_sha256$iterations$salt$hash."""

    salt = secrets.token_hex(16)

    digest = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode("utf-8"),
        salt.encode("utf-8"),
        PASSWORD_ITERATIONS,
    )

    return "pbkdf2_sha256${}${}${}".format(
        PASSWORD_ITERATIONS,
        salt,
        digest.hex(),
    )


def check_password(password, stored):
    """Compare a password with the stored hash in constant time."""

    try:
        algorithm, iterations, salt, digest = str(stored).split("$")

        candidate = hashlib.pbkdf2_hmac(
            "sha256",
            password.encode("utf-8"),
            salt.encode("utf-8"),
            int(iterations),
        ).hex()

    except (ValueError, TypeError):
        return False

    if algorithm != "pbkdf2_sha256":
        return False

    return secrets.compare_digest(candidate, digest)


def sign_in(username=None, phone=None):
    """Start a fresh session for the signed-in member."""

    session.clear()

    session.permanent = True

    if username:
        session["username"] = username

    if phone:
        session["phone"] = phone


@app.route("/auth/signup", methods=["POST"])
def signup():
    data = request.get_json(silent=True) or {}

    username = str(data.get("username") or "").strip()
    password = str(data.get("password") or "")
    confirm = str(data.get("confirm") or "")
    role = str(data.get("role") or "user").strip().lower()

    if role not in ("user", "admin"):
        return jsonify({"error": "Choose whether you are a user or an administrator."}), 400

    if not USERNAME_PATTERN.match(username):
        return jsonify({
            "error": "Username must be 3-20 letters, numbers or underscores."
        }), 400

    if len(password) < 6:
        return jsonify({
            "error": "Password must be at least 6 characters."
        }), 400

    if password != confirm:
        return jsonify({"error": "The passwords do not match."}), 400

    connection = connect()

    taken = connection.execute(
        "SELECT 1 FROM users WHERE LOWER(username) = LOWER(%s)",
        (username,),
    ).fetchone()

    if taken:
        connection.close()

        return jsonify({
            "error": "That username is already taken. Try logging in."
        }), 409

    connection.execute(
        "INSERT INTO users (username, password, role) VALUES (%s, %s, %s)",
        (username, hash_password(password), role),
    )
    connection.commit()
    connection.close()

    sign_in(username=username)

    return jsonify({"ok": True, "username": username, "role": role})


@app.route("/auth/login", methods=["POST"])
def login():
    data = request.get_json(silent=True) or {}

    username = str(data.get("username") or "").strip()
    password = str(data.get("password") or "")

    if not username or not password:
        return jsonify({"error": "Enter your username and password."}), 400

    connection = connect()

    row = connection.execute(
        "SELECT username, password, role FROM users WHERE LOWER(username) = LOWER(%s)",
        (username,),
    ).fetchone()

    connection.close()

    if row is None or not check_password(password, row[1]):
        return jsonify({
            "error": "Wrong username or password. Please try again."
        }), 400

    sign_in(username=row[0])

    return jsonify({
        "ok": True,
        "username": row[0],
        "role": row[2] or "user",
    })


@app.route("/auth/request-otp", methods=["POST"])
def request_otp():
    data = request.get_json(silent=True) or {}

    phone = normalize_phone(data.get("phone"))

    if phone is None:
        return jsonify({"error": "Enter a valid 10-digit mobile number."}), 400

    now = int(time.time())

    connection = connect()

    row = connection.execute(
        "SELECT requested_at FROM otps WHERE phone = %s",
        (phone,),
    ).fetchone()

    if row and now - row[0] < OTP_RESEND_GAP:
        connection.close()

        wait = OTP_RESEND_GAP - (now - row[0])

        return jsonify({
            "error": "Please wait " + str(wait) +
                     " seconds before requesting another OTP."
        }), 429

    code = "{:0{}d}".format(secrets.randbelow(10 ** OTP_LENGTH), OTP_LENGTH)

    connection.execute(
        """
        INSERT INTO otps (phone, code, expires_at, attempts, requested_at)
        VALUES (%s, %s, %s, 0, %s)
        ON CONFLICT (phone) DO UPDATE SET
            code = EXCLUDED.code,
            expires_at = EXCLUDED.expires_at,
            attempts = 0,
            requested_at = EXCLUDED.requested_at
        """,
        (phone, code, now + OTP_TTL, now),
    )
    connection.commit()
    connection.close()

    delivered = deliver_otp(phone, code)

    payload = {
        "ok": True,
        "phone": phone,
        "expiresIn": OTP_TTL,
        "resendAfter": OTP_RESEND_GAP,
    }

    if not delivered:
        # Demo mode: the page can show the code until an SMS provider is added
        payload["demoOtp"] = code

    return jsonify(payload)


@app.route("/auth/verify-otp", methods=["POST"])
def verify_otp():
    data = request.get_json(silent=True) or {}

    phone = normalize_phone(data.get("phone"))
    code = str(data.get("otp") or "").strip()

    if phone is None:
        return jsonify({"error": "Enter a valid 10-digit mobile number."}), 400

    if len(code) != OTP_LENGTH or not code.isdigit():
        return jsonify({"error": "Enter the 6-digit OTP."}), 400

    now = int(time.time())

    connection = connect()

    row = connection.execute(
        "SELECT code, expires_at, attempts FROM otps WHERE phone = %s",
        (phone,),
    ).fetchone()

    if row is None:
        connection.close()

        return jsonify({
            "error": "No OTP found for this number. Request a new one."
        }), 400

    stored_code, expires_at, attempts = row

    if now > expires_at:
        connection.execute("DELETE FROM otps WHERE phone = %s", (phone,))
        connection.commit()
        connection.close()

        return jsonify({"error": "That OTP has expired. Request a new one."}), 400

    if attempts >= OTP_MAX_ATTEMPTS:
        connection.execute("DELETE FROM otps WHERE phone = %s", (phone,))
        connection.commit()
        connection.close()

        return jsonify({
            "error": "Too many wrong attempts. Request a new OTP."
        }), 400

    if not secrets.compare_digest(stored_code, code):
        connection.execute(
            "UPDATE otps SET attempts = attempts + 1 WHERE phone = %s",
            (phone,),
        )
        connection.commit()
        connection.close()

        left = OTP_MAX_ATTEMPTS - attempts - 1

        return jsonify({
            "error": "Incorrect OTP. " + str(left) + " attempt(s) left."
        }), 400

    # Correct: the code is single-use, so drop it and sign the number in

    connection.execute("DELETE FROM otps WHERE phone = %s", (phone,))
    connection.commit()
    connection.close()

    sign_in(phone=phone)

    return jsonify({"ok": True, "phone": phone})


