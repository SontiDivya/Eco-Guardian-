def build_conninfo():
    """Return the PostgreSQL connection string, or stop with a clear error."""

    url = (os.environ.get("DATABASE_URL") or "").strip()

    if not url:
        raise SystemExit(
            "DATABASE_URL is not set. Add it to backend/.env, for example:\n"
            "  DATABASE_URL=postgresql://user:password@host/database?sslmode=require"
        )

    # Neon requires TLS; add it only when the URL does not say so already.

    if "sslmode=" not in url:
        url += ("&" if "?" in url else "?") + "sslmode=require"

    return url


def connect():
    """One PostgreSQL connection, used exactly like sqlite3.connect() was."""

    return psycopg.connect(build_conninfo())


# Signing key for the login session cookie. It is kept between restarts so
# people stay signed in; set FLASK_SECRET_KEY in the environment to override.

SECRET_FILE = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    ".secret_key",
)


def load_secret_key():
    key = os.environ.get("FLASK_SECRET_KEY", "").strip()

    if key:
        return key

    if os.path.exists(SECRET_FILE):
        with open(SECRET_FILE) as file:
            saved = file.read().strip()

        if saved:
            return saved

    new_key = secrets.token_hex(32)

    with open(SECRET_FILE, "w") as file:
        file.write(new_key)

    return new_key


app.secret_key = load_secret_key()


